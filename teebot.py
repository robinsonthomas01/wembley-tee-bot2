def unpack(into: pathlib.Path = pathlib.Path("bot")) -> list[str]:
    """
    Write the modules to disk, replacing any that have changed.

    This file is the source of truth. An earlier version only wrote missing
    files, which meant pasting an updated bundle silently did nothing.
    """
    raw = zlib.decompress(base64.b64decode(PAYLOAD)).decode("utf-8")
    into.mkdir(exist_ok=True)
    added, updated = [], []
    for chunk in raw.split("\n#--FILE--:"):
        if not chunk.strip():
            continue
        name, _, body = chunk.partition("\n")
        name = name.strip().lstrip("#--FILE--:").strip()
        if not name:
            continue
        target = into / name
        if not target.exists():
            target.write_text(body, encoding="utf-8")
            added.append(name)
        elif target.read_text(encoding="utf-8") != body:
            target.write_text(body, encoding="utf-8")
            updated.append(name)
    if added:
        print(f"Unpacked {len(added)} new module(s): {', '.join(added)}")
    if updated:
        print(f"Updated {len(updated)} changed module(s): {', '.join(updated)}")
    if not added and not updated:
        print("bot/ already matches this bundle.")
    return added + updated


def main(argv: list[str]) -> int:
    unpack()
    sys.path.insert(0, str(pathlib.Path.cwd()))

    if not argv:
        print(__doc__)
        return 1
    cmd, rest = argv[0], argv[1:]

    if cmd == "setup":
        import runpy
        rc = 0
        try:
            runpy.run_path("recon.py", run_name="__main__")
        except SystemExit as e:
            rc = e.code or 0
        from bot import calibrate
        try:
            calibrate.run(write=True)
        except Exception as e:
            print(f"Could not check the lead time: {e}")
        return rc

    if cmd in ("drop", "drop-now"):
        from bot import drop
        return drop.run(fire_now=(cmd == "drop-now"))

    if cmd in ("scan", "scan-now"):
        from bot import scan
        return scan.run()

    if cmd == "snapshot":
        from bot import snapshot
        return snapshot.run()

    if cmd == "calibrate":
        from bot import calibrate
        return calibrate.run(write="--write" in rest)

    if cmd == "act":
        from bot import act
        import argparse
        ap = argparse.ArgumentParser(prog="teebot.py act")
        ap.add_argument("--do", required=True,
                        choices=["book", "cancel", "move", "refresh"])
        ap.add_argument("--resource"); ap.add_argument("--date")
        ap.add_argument("--time"); ap.add_argument("--players", type=int, default=1)
        ap.add_argument("--cancel-url", dest="cancel_url")
        ap.add_argument("--token", default="")
        return act.run(ap.parse_args(rest))

    print(f"Unknown command: {cmd}")
    print(__doc__)
    return 1


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except Exception as exc:
        print(f"error: {exc}", file=sys.stderr)
        sys.exit(1)
